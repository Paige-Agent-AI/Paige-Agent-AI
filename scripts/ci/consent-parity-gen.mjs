#!/usr/bin/env node
/**
 * consent-parity-gen — one fixture, two implementations, and drift turns CI red (E09 Slice 6, M8).
 *
 * The rule "may this business email or text this client right now?" is implemented twice:
 *   - in TypeScript, by runPreSend (+ tenantConsent, + normalizeAddress) in
 *     supabase/functions/_shared/, which every send path calls before a provider send; and
 *   - in SQL, by public._client_communication_state (+ public._comms_normalize_address), which the
 *     customer's and the owner's preference cards read.
 *
 * pgTAP cannot read a JSON file (hosted and CI databases bar pg_read_file), and the Deno test cannot
 * call SQL offline. So supabase/tests/fixtures/consent-parity.json is the ONE source:
 *   - supabase/functions/_shared/consent-parity.test.ts reads it and asserts the TypeScript;
 *   - this script GENERATES supabase/tests/customer_portal_consent_parity.sql from it, which asserts
 *     the SQL against the same rows and the same expectations.
 *
 *   node scripts/ci/consent-parity-gen.mjs           # regenerate the pgTAP file
 *   node scripts/ci/consent-parity-gen.mjs --check   # CI: fail if the committed file is stale
 */
import { readFileSync, writeFileSync, existsSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..", "..");
const FIXTURE = path.join(ROOT, "supabase/tests/fixtures/consent-parity.json");
const OUT = path.join(ROOT, "supabase/tests/customer_portal_consent_parity.sql");

const TENANT = "e0972000-0000-4000-8000-000000000001";
const OWNER = "e0971000-0000-4000-8000-000000000001";
const CLIENT = "e0973000-0000-4000-8000-000000000001";

const lit = (v) => (v === null || v === undefined ? "NULL" : `'${String(v).replace(/'/g, "''")}'`);

export function generate(fixture) {
  const { client, normalizer, cases } = fixture;
  const stateChecks = 6; // email, email_set_by, sms, sms_set_by, updates, updates_set_by
  const extraChecks = 3; // presend_email, presend_sms, tenant_consent_email
  const plan = normalizer.length + cases.length * (stateChecks + extraChecks);
  const out = [];
  out.push(
    "-- GENERATED by scripts/ci/consent-parity-gen.mjs from supabase/tests/fixtures/consent-parity.json.",
    "-- DO NOT EDIT. Edit the fixture and regenerate; CI fails when this file is stale.",
    "-- The SQL half of the consent parity proof (E09 Slice 6, M8): public._comms_normalize_address and",
    "-- public._client_communication_state against the SAME rows and expectations the TypeScript deciders",
    "-- (runPreSend, tenantConsent, normalizeAddress) are held to in _shared/consent-parity.test.ts.",
    "BEGIN;",
    `SELECT plan(${plan});`,
    "INSERT INTO auth.users(id,aud,role,email,email_confirmed_at,raw_app_meta_data) VALUES",
    ` ('${OWNER}','authenticated','authenticated','parity-owner@tests.invalid',now(),'{"comms_provider_execution":"disabled"}');`,
    "INSERT INTO public.tenants(id,slug,name,status,account_type,account_number_prefix,account_number,features) VALUES",
    ` ('${TENANT}','test-tenant-e09-consent-parity','Parity Studio','active','standalone','E09CP',9471001,'{}');`,
    "INSERT INTO public.clients(id,tenant_id,created_by,first_name,last_name,status) VALUES",
    ` ('${CLIENT}','${TENANT}','${OWNER}','Parity','Client','active');`,
    "INSERT INTO public.client_contact_methods(tenant_id,client_id,kind,value,is_primary,position) VALUES",
    ` ('${TENANT}','${CLIENT}','email',${lit(client.email)},true,0),`,
    ` ('${TENANT}','${CLIENT}','phone',${lit(client.phone)},true,1);`,
    "-- The test mirror of runPreSend steps 2-3 for one send (the TypeScript itself is proven in Deno).",
    "CREATE FUNCTION pg_temp.presend(_ch text, _to text) RETURNS text LANGUAGE sql AS $$",
    "  SELECT CASE",
    `    WHEN EXISTS (SELECT 1 FROM public.paige_suppressions s WHERE s.tenant_id='${TENANT}' AND s.channel=_ch`,
    `      AND (s.contact_id='${CLIENT}' OR s.address_normalized=public._comms_normalize_address(_ch,_to))) THEN 'blocked_suppressed'`,
    `    WHEN _ch='sms' AND coalesce((SELECT e.action FROM public.paige_consent_events e WHERE e.tenant_id='${TENANT}' AND e.channel=_ch`,
    `      AND (e.contact_id='${CLIENT}' OR e.address_normalized=public._comms_normalize_address(_ch,_to))`,
    "      ORDER BY e.created_at DESC, e.id DESC LIMIT 1),'none') <> 'granted' THEN 'blocked_no_consent'",
    "    ELSE 'proceed' END $$;",
    "-- tenantConsent: the latest email event of ANY topic, by contact or by the normalized address.",
    "CREATE FUNCTION pg_temp.tenant_consent(_to text) RETURNS text LANGUAGE sql AS $$",
    `  SELECT coalesce((SELECT e.action FROM public.paige_consent_events e WHERE e.tenant_id='${TENANT}' AND e.channel='email'`,
    `    AND (e.contact_id='${CLIENT}' OR e.address_normalized=public._comms_normalize_address('email',_to))`,
    "    ORDER BY e.created_at DESC, e.id DESC LIMIT 1),'none') $$;",
    "",
    "-- Normalizer parity",
  );
  for (const n of normalizer) {
    out.push(`SELECT is(public._comms_normalize_address(${lit(n.channel)},${lit(n.input)}),${lit(n.expect)},${lit(`normalize ${n.channel}: ${JSON.stringify(n.input)}`)});`);
  }
  out.push("", "-- State parity");
  for (const c of cases) {
    out.push(
      `-- ${c.name}`,
      // A trusted (no signed-in user) context may clear any row; customer_portal rows need the
      // customer's transaction-local marker, exactly as the portal RPC sets it.
      `DELETE FROM public.paige_suppressions WHERE tenant_id='${TENANT}';`,
      `DELETE FROM public.paige_consent_events WHERE tenant_id='${TENANT}';`,
      `SELECT set_config('paige.customer_consent_write','on',true), set_config('paige.customer_consent_contact','${CLIENT}',true);`,
    );
    for (const r of c.rows) {
      const contact = r.key === "address" ? "NULL" : `'${CLIENT}'`;
      // A row's own `address` (a merge moved another record's opt-out here) replaces the primary one.
      const raw = r.address ?? (r.channel === "sms" ? client.phone : client.email);
      const addr = r.key === "contact" ? "NULL" : `public._comms_normalize_address(${lit(r.channel)},${lit(raw)})`;
      const at = `timestamptz '2026-10-01 00:00:00+00' + ${Number(r.at)} * interval '1 minute'`;
      if (r.table === "suppression") {
        out.push(`INSERT INTO public.paige_suppressions(tenant_id,contact_id,address_normalized,channel,reason,source,created_at) VALUES ('${TENANT}',${contact},${addr},${lit(r.channel)},${lit(r.reason)},${lit(r.source)},${at});`);
      } else {
        out.push(`INSERT INTO public.paige_consent_events(tenant_id,contact_id,address_normalized,channel,topic,action,source,created_at) VALUES ('${TENANT}',${contact},${addr},${lit(r.channel)},${lit(r.topic)},${lit(r.action)},${lit(r.source)},${at});`);
      }
    }
    out.push(`SELECT set_config('paige.customer_consent_write','',true), set_config('paige.customer_consent_contact','',true);`);
    const e = c.expect;
    const st = `public._client_communication_state('${TENANT}','${CLIENT}')`;
    const label = (k) => lit(`${c.name}: ${k}`);
    out.push(
      `SELECT is(${st}#>>'{email,state}',${lit(e.email)},${label("email")});`,
      `SELECT is(${st}#>>'{email,set_by}',${lit(e.email_set_by)},${label("email set_by")});`,
      `SELECT is(${st}#>>'{sms,state}',${lit(e.sms)},${label("sms")});`,
      `SELECT is(${st}#>>'{sms,set_by}',${lit(e.sms_set_by)},${label("sms set_by")});`,
      `SELECT is(${st}#>>'{updates,state}',${lit(e.updates)},${label("updates")});`,
      `SELECT is(${st}#>>'{updates,set_by}',${lit(e.updates_set_by)},${label("updates set_by")});`,
      `SELECT is(pg_temp.presend('email',${lit(client.email)}),${lit(e.presend_email)},${label("presend email")});`,
      `SELECT is(pg_temp.presend('sms',${lit(client.phone)}),${lit(e.presend_sms)},${label("presend sms")});`,
      `SELECT is(pg_temp.tenant_consent(${lit(client.email)}),${lit(e.tenant_consent_email)},${label("tenantConsent email")});`,
    );
  }
  out.push("", "SELECT * FROM finish();", "ROLLBACK;", "");
  return out.join("\n");
}

function main() {
  const fixture = JSON.parse(readFileSync(FIXTURE, "utf8"));
  const sql = generate(fixture);
  if (process.argv.includes("--check")) {
    const current = existsSync(OUT) ? readFileSync(OUT, "utf8") : "";
    if (current !== sql) {
      console.error(`consent-parity-gen: ${path.relative(ROOT, OUT)} is stale against ${path.relative(ROOT, FIXTURE)}.`);
      console.error("Run `node scripts/ci/consent-parity-gen.mjs` and commit the result.");
      process.exit(1);
    }
    console.log(`consent-parity-gen: ${path.relative(ROOT, OUT)} matches the fixture (${fixture.normalizer.length} normalizer + ${fixture.cases.length} state cases).`);
    return;
  }
  writeFileSync(OUT, sql);
  console.log(`consent-parity-gen: wrote ${path.relative(ROOT, OUT)}`);
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) main();
