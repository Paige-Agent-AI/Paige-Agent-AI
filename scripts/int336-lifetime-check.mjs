import assert from 'node:assert/strict';
import {createInteractiveLifetime} from '../supabase/functions/_shared/paige-turn/interactive.ts';
let releaseCount=0;
const life=createInteractiveLifetime({release:async()=>releaseCount++});
await life.handlerFinished(); await life.handlerFinished(); assert.equal(releaseCount,1);
releaseCount=0;
const streaming=createInteractiveLifetime({release:async()=>releaseCount++});
let settle; const work=new Promise(resolve=>settle=resolve);
const running=streaming.runStream(async()=>{await work;});
await streaming.handlerFinished(); assert.equal(releaseCount,0,'handler return must not release stream executor');
settle(); await running; assert.equal(releaseCount,1);
await streaming.handlerFinished(); assert.equal(releaseCount,1);
releaseCount=0;
const throwing=createInteractiveLifetime({release:async()=>releaseCount++});
await assert.rejects(throwing.runStream(async()=>{throw Error('persistence failed')}));
assert.equal(releaseCount,1);
releaseCount=0;
const effects=createInteractiveLifetime({release:async()=>releaseCount++});
let settleEffect; const effect=new Promise(resolve=>settleEffect=resolve);
const performing=effects.runStream(async()=>{await effect;});
await effects.handlerFinished(); assert.equal(releaseCount,0,'inflight consequence must retain executor');
settleEffect(); await performing; assert.equal(releaseCount,1);
console.log('PASS: early exit, idempotence, asynchronous stream transfer, persistence throw, effect settlement');
