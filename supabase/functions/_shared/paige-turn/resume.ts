// C4a — ONE RESUME MODEL for a paused objective (docs/delivery/paige-conversational-loop-c4.md).
//
// WAIT_APPROVAL, ASK_USER and WAIT_WORK are three reasons one objective paused, not three workflow
// systems. This module is the pure half of resuming it; the chat handler (`paige-ai-chat`) does the
// IO. C4c adds the ANSWER kind (bottom of this file): the question turn IS the ask, the person's
// answer is bound to it once, and PAIGE continues the same objective. C4a ships the APPROVAL kind: when the person approves a stored proposal, the server carries
// the exact approved act forward — rebuilt from the stored row, never regenerated by the model —
// runs it once through the existing gate, and then lets PAIGE continue the same objective. C4b
// extends the same seam to DOOR proposals (CRM, Sales, publish): the rebuilt call is handed to the
// chat's existing door branch, and the door — still the only claim site — runs its stored request.
//
// WHAT THIS MODULE NEVER DOES, so the authority story stays in one place:
//  - it grants nothing. A synthetic call is only a CALL; the existing gate still decides, the
//    existing compare-and-set claim on `consumed_at` still makes it exactly-once, and the stored
//    arguments still overwrite whatever the call carried;
//  - it reads no request field for authority. The row it is handed was selected by the handler
//    under the caller's own user, tenant, thread and client scope;
//  - it writes no prose into a turn record. `turn_state.resumed` is a closed enum; the per-act
//    outcomes live beside it in `bundle_ref.paige_resume` as closed enums and the caller's own
//    tool names (already on the same row in `paige_confirm`).
//
// Pure TypeScript with no Deno API and no runtime imports beyond the sibling outcome module, so
// Deno, Node (the authz harness) and vitest all load it.

